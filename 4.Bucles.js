// Bucles(loop o ciclo):

/*
Un bucle es una estructura de control que permite ejecutar un bloque de codigo varias veces, hasta que
una condicion deje de cumplirse
su funcion es repetir una o mas veces una instruccion

para que sirven:
- Mostrar una lista de productos
- Recorrer un arreglo
- Realizar una operacion repetitiva
*/

// Como se dividen los bucles:
/*
for: cuando sabes cuantas veces repetir
while: cuando no sabes cuantas veces repetir
do...while: debe ejecutarse almenos una vez
for...of: recorrer elementos de un iterable(array,string,etc)
for..in: recorrer las propiedades de un objeto
foreach(): metodos de los arrays para recorrer elementos

1. For:
Se utiliza cuando sabes cuantas veces queremos que se repita una accion
sintaxis:
for (inicialización; condición; actualización) {
    // codigo a repetir
}





*/